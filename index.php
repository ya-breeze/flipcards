        </p>
        <h2>Предистория: 📜</h2>
        <p>На нашем ютюб канале <a href="https://www.youtube.com/channel/UCZZAtmyerOqOgbHlxrpEUvw" target="_blank">"Шестаковы в Италии"</a> мы не однократно рассказывали что начинали изучать итальянский язык по урокам Дмитрия Петрова "Полиглот итальянский за 16 часов", на мой взгляд это лучший метод для вхождения в язык, с тех пор я уже сдал несколько государственных(итальянских) экзаменов.<br>Но есть одно "но" потратить придется значительно больше чем 16 часов, для этого я и сделал это приложение. 🎓</p>
        <h2>Рекомендации по изучению слов: 📚</h2>
        <p>Все слова из уроков нужно заучить, да просто заучить до тех пор когда правильный перевод слова будет приходить в голову моментально, без задержки ни на 1 секунду.<br>У меня уходило 1-2 дня на урок, по 15-20 повторений в день. Нет смысла переходить к следующему уроку, если вы не добились нужного результата на текущем уроке.<br>При запоминании слов нового урока нужно обязательно повторять как минимум по 2 раза в день каждый пройденный урок иначе успеха не будет. При должном упорстве за два месяца можно дойти с 0 до уровня <abbr title="Pre-Intermediate: Вы можете рассказывать о себе, своей семье, профессии, предпочтениях (в музыке, кухни, хобби, время года…). Понимаете, тексты рекламы, объявления в аэропорту, магазине, надписи на продуктах, открытках, знаете, как писать личные и деловые письма. Читать и пересказывать не очень сложные тексты.">A2</abbr> 📖</p>

        <h2>Как пользоваться: 🤔</h2>
        <p>После просмотра занятия переходить на <a href="table.php">страницу с таблицей</a> и выбрать соответствующий урок, повторить все пары слов, обязательно кликая на них, чтоб прослушать произношение, после того как все повторили, переходить на <a href="cards.php">страницу карточек</a>, где непосредственно тренироваться. 🔖
        <br><br><span style="color:red; font-weight: bold;">NEW!</span> <span style="font-weight: bold;">Я реализовал текстовые <a href="topics.php">📖 Топики</a> для чтения с аудио 🔊 прослушиванием. Это то чего мне так не хватало во время изучения, у вас теперь есть! Пополнение текстами возможно только при вашей <a href="donate.php">поддержке 👍</a></span>
             
